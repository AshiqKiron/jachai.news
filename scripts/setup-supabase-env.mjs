#!/usr/bin/env node
/**
 * Writes backend/.env + frontend/.env.local for hosted Supabase (project xbadshfnetqzpvdavaef).
 * Usage:
 *   node scripts/setup-supabase-env.mjs
 * Or non-interactive:
 *   SUPABASE_DB_PASSWORD=... SUPABASE_ANON_KEY=... [SUPABASE_SERVICE_ROLE_KEY=...] \
 *     SUPABASE_POOLER_HOST=aws-0-ap-southeast-1.pooler.supabase.com \
 *     node scripts/setup-supabase-env.mjs --yes
 */
import { createInterface } from "node:readline";
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const PROJECT_REF = "xbadshfnetqzpvdavaef";
const SUPABASE_URL = `https://${PROJECT_REF}.supabase.co`;

function ask(rl, question, { secret = false, defaultValue = "" } = {}) {
  return new Promise((resolve) => {
    const def = defaultValue ? ` (${defaultValue})` : "";
    rl.question(`${question}${def}: `, (answer) => {
      resolve((answer || defaultValue).trim());
    });
  });
}

async function main() {
  const nonInteractive = process.argv.includes("--yes");
  let dbPassword = process.env.SUPABASE_DB_PASSWORD || "";
  let anonKey = process.env.SUPABASE_ANON_KEY || "";
  let serviceRole = process.env.SUPABASE_SERVICE_ROLE_KEY || "";
  let jwtSecret = process.env.SUPABASE_JWT_SECRET || "";
  let poolerHost =
    process.env.SUPABASE_POOLER_HOST || "aws-1-ap-south-1.pooler.supabase.com";

  if (!nonInteractive && (!dbPassword || !anonKey)) {
    const rl = createInterface({ input: process.stdin, output: process.stderr });
    console.error(
      `khatinews → Supabase project ${PROJECT_REF}\n` +
        "Get values from: Project Settings → Database (password, pooler URI host) and API (anon + service role).\n",
    );
    dbPassword = await ask(rl, "Database password", { secret: true });
    poolerHost = await ask(rl, "Pooler host from dashboard URI", {
      defaultValue: poolerHost,
    });
    anonKey = await ask(rl, "Anon key (public)");
    serviceRole = await ask(rl, "Service role key (optional, server-only)", {
      defaultValue: serviceRole,
    });
    jwtSecret = await ask(rl, "JWT secret (optional)", { defaultValue: jwtSecret });
    rl.close();
  }

  if (!dbPassword || !anonKey) {
    console.error("Missing SUPABASE_DB_PASSWORD or SUPABASE_ANON_KEY.");
    process.exit(1);
  }

  const encodedPassword = encodeURIComponent(dbPassword);
  const poolerUrl = `postgresql://postgres.${PROJECT_REF}:${encodedPassword}@${poolerHost}:6543/postgres?sslmode=require`;

  const backendEnv = `# Generated by scripts/setup-supabase-env.mjs — see docs/DATABASE.md
DATABASE_POOLER_URL=${poolerUrl}
DATABASE_POOL_MODE=pgbouncer

SUPABASE_URL=${SUPABASE_URL}
${jwtSecret ? `SUPABASE_JWT_SECRET=${jwtSecret}\n` : "# SUPABASE_JWT_SECRET=\n"}${serviceRole ? `SUPABASE_SERVICE_ROLE_KEY=${serviceRole}\n` : "# SUPABASE_SERVICE_ROLE_KEY=\n"}
REDIS_URL=redis://127.0.0.1:6379/0
INGEST_ASYNC_ENABLED=true
INGEST_SCHEDULER_ENABLED=true
CORS_ORIGINS=["http://localhost:3000"]

GROQ_API_KEY=
GEMINI_API_KEY=
AI_PROVIDER=groq
INGEST_API_KEY=
ADMIN_API_KEY=
`;

  const frontendPath = join(root, "frontend", ".env.local");
  let frontendExtras = "";
  if (existsSync(frontendPath)) {
    const keep = readFileSync(frontendPath, "utf8")
      .split("\n")
      .filter(
        (line) =>
          line.trim() &&
          !/^NEXT_PUBLIC_SUPABASE_/i.test(line) &&
          !/^SUPABASE_SERVICE_ROLE_KEY=/i.test(line) &&
          !/^NEXT_PUBLIC_API_URL=/i.test(line) &&
          !/^API_URL=/i.test(line),
      );
    if (keep.length) frontendExtras = `${keep.join("\n")}\n`;
  }

  const frontendEnv = `${frontendExtras}NEXT_PUBLIC_API_URL=/api/v1
API_URL=http://127.0.0.1:3001/api/v1

NEXT_PUBLIC_SUPABASE_URL=${SUPABASE_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
${serviceRole ? `SUPABASE_SERVICE_ROLE_KEY=${serviceRole}\n` : "# SUPABASE_SERVICE_ROLE_KEY=\n"}
`;

  writeFileSync(join(root, "backend", ".env"), backendEnv, "utf8");
  writeFileSync(frontendPath, frontendEnv, "utf8");

  console.log("Wrote backend/.env and frontend/.env.local");
  console.log("\nNext steps:");
  console.log("  1. SQL Editor: CREATE EXTENSION IF NOT EXISTS vector;");
  console.log("  2. Apply supabase/migrations/*.sql (or: cd supabase && npx supabase db push)");
  console.log("  3. npm run dev:backend   # creates news tables + backend/migrations");
  console.log("  4. npm run dev:frontend");
  console.log("  5. /admin → pull RSS or upload feed → articles appear on home");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});